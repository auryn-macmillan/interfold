out,tag=sys.argv[1],sys.argv[2]
try:
  d=json.load(open(out+f'/{tag}_gates.json'))
  fns=d.get('functions',[]); g=sum(f.get('circuit_size',0) for f in fns); ac=sum(f.get('acir_opcodes',0) for f in fns)
  wall=0.0; peak=0
  for l in open(out+f'/{tag}_timev.log',errors='replace'):
    if 'Elapsed (wall clock)' in l:
      t=l.split(':',1)[1].strip().rsplit(' ',1)[-1]
      try: p=t.split(':'); wall=float(p[0])*60+float(p[1])
      except Exception: pass
    if 'Maximum resident set size' in l:
      peak=int(l.split()[-1])
  line=f"ROUND=r175 LEG={tag} BASE=6a8afd39d DATE={datetime.datetime.utcnow().strftime('%Y-%m-%dT%H:%M:%SZ')} GATES={g} ACIR={ac} WALL={wall:.1f}s PEAK_KB={peak}"
except Exception as e:
  line=f'ROUND=r175 LEG={tag} PARSE_ERR={e}'
open(out+f'/{tag}.r175','w').write(line+"\n")
print(line)
PY
}
