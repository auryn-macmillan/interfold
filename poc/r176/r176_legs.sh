#!/usr/bin/env bash
# r176 - C1 eek/sk SOLO re-anchor leg (OPTIONAL coverage, r175 NEXT line) @ i5 tip e5161e6e8.
# Re-run the r170 harness (pk_generation.nr L186 eek / L189 sk solo line-comment) at the
# post-#2195 secure-50-coeffs shape. pk_generation.nr blob is BYTE-IDENTICAL r170->tip
# (d982ee78a, RAN git rev-parse 3-way); DEF blob MOVED (76bfde233 -> 186da8317, #2195/#2226
# config table). CLAIM under test: the r170 cross-leaf cell invariant (eek=sk=e1=36,864g
# per-poly identity cost, width-independent) is insensitive to the config-table fold.
# 3 legs, sha-pinned splice + byte-exact restore. MUST run under
# systemd-run --user --property=MemoryMax=infinity (r175 harness note).
set -u
export PATH="$HOME/.local/bin:$HOME/.nargo/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
R=/tmp/r176
OUT=/home/dev/i5-rebase-wt/poc/r176
mkdir -p "$OUT"
BASE=e5161e6e8bdc2624511aee6997bca324e6b20f3f
DEF=$R/circuits/lib/src/configs/default/mod.nr
PK=$R/circuits/lib/src/core/threshold/pk_generation.nr
TB=$R/circuits/bin/threshold
TGT=$TB/target
ART=$TGT/pk_generation.json
# PRE shas pinned from disk THIS round (i5-rebase-wt @ e5161e6e8, RAN sha256sum):
PRE_DEF=17c3347ea8b3e1d5dbd7350bd3c1c1ade6dd349cdbfea60fc0fa87ee05841a02
PRE_PK=8e37436bdca8ff0c58bc4307e2ab9ace2ed40a0d6d5211e244818a23ef50436a
log(){ echo "[$(date -u +%FT%TZ)] $*" | tee -a "$OUT/log.r176"; }
[ "$(awk '/^MemAvailable:/{print $2}' /proc/meminfo)" -ge 12000000 ] || { log LOW_MEM; exit 96; }
if [ -d "$R" ]; then
  HEAD_NOW=$(git -C "$R" rev-parse HEAD 2>/dev/null)
  if [ "$HEAD_NOW" = "$BASE" ]; then log "WORKTREE-EXISTING-REUSE @ $HEAD_NOW"; else log "WORKTREE-EXISTS-WRONG-SHA $HEAD_NOW"; exit 96; fi
else
  git -C /home/dev/interfold-research/interfold worktree add --detach "$R" "$BASE" >> "$OUT/log.r176" 2>&1 || { log WT_FAIL; exit 96; }
fi
cd "$R" || { log ERR_CD; exit 98; }
[ "$(git rev-parse HEAD)" = "$BASE" ] || { log BASE-NOT-LOCKED; exit 97; }
log "HEAD=$(git rev-parse HEAD)"
[ "$(sha256sum "$DEF" | cut -d' ' -f1)" = "$PRE_DEF" ] || { log PRE_DEF_MISMATCH; exit 99; }
[ "$(sha256sum "$PK"  | cut -d' ' -f1)" = "$PRE_PK"  ] || { log PRE_PK_MISMATCH;  exit 99; }
cp -f "$DEF" "$OUT/zz_default_mod.nr.bak"
cp -f "$PK"  "$OUT/zz_pk_generation.nr.bak"
restore(){
  cp -f "$OUT/zz_default_mod.nr.bak" "$DEF"
  cp -f "$OUT/zz_pk_generation.nr.bak" "$PK"
  if [ "$(sha256sum "$DEF" | cut -d' ' -f1)" = "$PRE_DEF" ] && [ "$(sha256sum "$PK" | cut -d' ' -f1)" = "$PRE_PK" ]; then
    log "RESTORED rc=0"; return 0
  fi
  log "RESTORED rc=1 (sha mismatch!)"; return 1
}
trap 'log INTERRUPT-RESTORE; restore' TERM INT
flip_def(){
python3 - "$DEF" <<'PY'
import sys
p=sys.argv[1]; a=open(p,encoding='utf-8').read()
s=a.replace('Auto-generated by build-circuits.ts for preset: insecure-64',
            'Auto-generated by build-circuits.ts for preset: secure-8192')
s=s.replace('pub use super::insecure::dkg;','pub use super::secure::dkg;')
s=s.replace('pub use super::insecure::threshold;','pub use super::secure::threshold;')
assert s!=a, "preset flip miss"
open(p,'w').write(s); print("FLIP_OK")
PY
}
compile_one(){ # $1 TAG ; artifact at $ART (workspace target, #2236); bb-gates -> ${TAG}_gates.json
  local tag=$1
  cd "$TB" || { log "${tag}_CD_FAIL"; return 96; }
  rm -f "$ART"
  local s e rc
  s=$(date +%s)
  taskset -c 0-3 /usr/bin/time -v nargo compile --force > "$OUT/${tag}_stdout.log" 2> "$OUT/${tag}_timev.log"
  rc=$?
  e=$(date +%s)
  echo "$((e-s))s" > "$OUT/${tag}_wall.raw"
  log "$tag rc=$rc wall=$((e-s))s"
  cd "$R" || return 99
  [ $rc -ne 0 ] && return $rc
  [ -s "$ART" ] || return 100
  cp -f "$ART" "$OUT/${tag}_fresh.json"
  bb gates -b "$OUT/${tag}_fresh.json" -t noir-recursive-no-zk > "$OUT/${tag}_gates.json" 2> "$OUT/${tag}_gates_err.log"
  return 0
}
caption(){
  local tag=$1
  python3 - "$OUT" "$tag" <<'PY'
import json,sys,datetime
out,tag=sys.argv[1],sys.argv[2]
try:
  d=json.load(open(out+f'/{tag}_gates.json'))
  fns=d.get('functions',[]); g=sum(f.get('circuit_size',0) for f in fns); ac=sum(f.get('acir_opcodes',0) for f in fns)
  wall=0.0; peak=0
  for l in open(out+f'/{tag}_timev.log',errors='replace'):
    if 'Elapsed (wall clock)' in l:
      t=l.split(':',1)[1].strip().rsplit(' ',1)[-1]
      try: p=t.split(':'); wall=float(p[0])*60+float(p[1])
      except Exception: pass
    if 'Maximum resident set size' in l:
      peak=int(l.split()[-1])
  line=f"ROUND=r176 LEG={tag} BASE=e5161e6e8 DATE={datetime.datetime.utcnow().strftime('%Y-%m-%dT%H:%M:%SZ')} GATES={g} ACIR={ac} WALL={wall:.1f}s PEAK_KB={peak}"
except Exception as e:
  line=f'ROUND=r176 LEG={tag} PARSE_ERR={e}'
open(out+f'/{tag}.r176','w').write(line+"\n")
print(line)
PY
}
### ====== LEG A1: unblunt secure-8192 re-anchor ======
flip_def || { log FLIP_FAIL_A1; restore; echo "R176_STATUS=A1_FLIPFAIL" | tee -a "$OUT/log.r176"; exit 107; }
compile_one r176A1_live; R_A1=$?
if [ $R_A1 -ne 0 ]; then log "A1 compile rc=$R_A1"; restore; echo "R176_STATUS=A1_FAIL rc=$R_A1" | tee -a "$OUT/log.r176"; exit 101; fi
caption r176A1_live || { log A1_PARSE_FAIL; restore; exit 102; }
log "LEG A1 DONE rc=$R_A1"
### ====== LEG E: eek solo NOP (L186 call line-commented; sk/e_sm/loop live) ======
python3 - "$PK" <<'PY'
import sys
p=sys.argv[1]; s=open(p,encoding='utf-8').read()
a='        self.eek.range_check_2bounds::<BIT_EEK>(self.configs.eek_bound, self.configs.eek_bound);'
n=s.count(a); assert n==1, "expected exactly 1 eek call site; got %d" % n
open(p,'w').write(s.replace(a,'        // R176-SOLO-NOP-E: '+a[8:])); print("NOP_E_OK")
PY
log "LEG E SPLICE APPLIED"
compile_one r176E_eek; R_E=$?
if [ $R_E -ne 0 ]; then log "E compile rc=$R_E"; restore; echo "R176_STATUS=E_FAIL rc=$R_E" | tee -a "$OUT/log.r176"; exit 103; fi
caption r176E_eek || { log E_PARSE_FAIL; restore; exit 104; }
log "LEG E DONE rc=$R_E"
### ====== LEG S: sk solo NOP (restore PK first, then L189 line-comment) ======
cp -f "$OUT/zz_pk_generation.nr.bak" "$PK"
python3 - "$PK" <<'PY'
import sys
p=sys.argv[1]; s=open(p,encoding='utf-8').read()
a='        self.sk.range_check_2bounds::<BIT_SK>(self.configs.sk_bound, self.configs.sk_bound);'
n=s.count(a); assert n==1, "expected exactly 1 sk call site; got %d" % n
open(p,'w').write(s.replace(a,'        // R176-SOLO-NOP-S: '+a[8:])); print("NOP_S_OK")
PY
log "LEG S SPLICE APPLIED"
compile_one r176S_sk; R_S=$?
restore; R_RESTORE=$?
log "RESTORE rc=$R_RESTORE after leg S"
if [ $R_S -ne 0 ]; then log "S compile rc=$R_S"; echo "R176_STATUS=S_FAIL rc=$R_S restore_rc=$R_RESTORE" | tee -a "$OUT/log.r176"; exit 105; fi
caption r176S_sk || { log S_PARSE_FAIL; echo "R176_STATUS=S_PARSE_FAIL" | tee -a "$OUT/log.r176"; exit 106; }
log "LEG S DONE rc=$R_S"
log "PORC_NONUNTRACKED=$(git -C $R status --porcelain | grep -v '^??' | wc -l)"
### ====== DELTAS (raw RAN only) ======
python3 - "$OUT" <<'PY'
import json,sys
def load(t):
  d=json.load(open(sys.argv[1]+"/"+t+"_gates.json"))
  return sum(f.get("circuit_size",0) for f in d.get("functions",[]))
def acir(t):
  d=json.load(open(sys.argv[1]+"/"+t+"_gates.json"))
  return sum(f.get("acir_opcodes",0) for f in d.get("functions",[]))
A=load("r176A1_live"); E=load("r176E_eek"); S=load("r176S_sk")
eek=A-E; sk=A-S
OLD=dict(A=1634722,E=1597858,S=1597853,eek=36864,sk=36869)
lines=[]
lines.append("r176 C1 eek/sk SOLO re-anchor @ e5161e6e8 (post-#2195 secure-50-coeffs shape):")
lines.append("  A1(unblunt)=%d  E(eek live->NOP)=%d  S(sk live->NOP)=%d"%(A,E,S))
lines.append("  ACIR: A1=%d E=%d S=%d"%(acir("r176A1_live"),acir("r176E_eek"),acir("r176S_sk")))
lines.append("  eek_solo(A-E)=%d g   sk_solo(A-S)=%d g   eek+sk=%d g"%(eek,sk,eek+sk))
lines.append("vs r170 @ a3bf52007 (OLD pre-fold shape):")
lines.append("  A1 old=%d new=%d delta=%+d"%(OLD["A"],A,A-OLD["A"]))
lines.append("  E  old=%d new=%d delta=%+d"%(OLD["E"],E,E-OLD["E"]))
lines.append("  S  old=%d new=%d delta=%+d"%(OLD["S"],S,S-OLD["S"]))
lines.append("  eek_solo old=%d new=%d delta=%+d"%(OLD["eek"],eek,eek-OLD["eek"]))
lines.append("  sk_solo  old=%d new=%d delta=%+d"%(OLD["sk"],sk,sk-OLD["sk"]))
lines.append("  cell invariant |eek-sk| = %d g (r170: 5 g); vs C3 e1 36864 (r161): eek delta=%+d"%(abs(eek-sk),eek-36864))
txt="\n".join(lines)+"\n"
open(sys.argv[1]+"/r176_delta.r176","w").write(txt)
print(txt)
PY
echo "R176_STATUS=ALL_OK" | tee -a "$OUT/log.r176"